"""Muninn's releases as published: which is the latest is what `muninn upgrade` installs (PyPI), and what each
brings is its GitHub release's notes, generated by git cliff (cliff.toml) under the headings New, Fixed, Faster and
Reverted."""

from __future__ import annotations

import logging
import re
from typing import Any, Callable, Sequence

import httpx
from packaging.version import InvalidVersion, Version

from muninn.core.releases import Notes

log = logging.getLogger(__name__)

REPOSITORY = "imaknas/muninn"
TIMEOUT_S = 15
FIXES = ("Fixed", "Faster", "Reverted")  # said together as fixes


class PublishedReleases:
    def __init__(self, index: Any, get: Callable[[str], Any] | None = None, repository: str = REPOSITORY):
        """`index`: the latest release (installs.PyPI); `get`: an HTTP GET."""
        self._index, self._repository = index, repository
        self._get = get or (lambda url: httpx.get(url, timeout=TIMEOUT_S, follow_redirects=True,
                                                  headers={"Accept": "application/vnd.github+json"}))

    def latest(self) -> str | None:
        release = self._index.latest()
        return release.version if release else None

    def notes(self, after: str, upto: str) -> Sequence[Notes]:
        try:
            r = self._get(f"https://api.github.com/repos/{self._repository}/releases?per_page=50")
            listed = r.json() if r.status_code == 200 else []
        except (httpx.HTTPError, ValueError) as e:
            log.info("could not read the release notes: %s", e)
            return []
        out = []
        for release in listed if isinstance(listed, list) else []:
            if release.get("draft") or release.get("prerelease"):
                continue
            try:
                version = Version(str(release.get("tag_name") or "").removeprefix("v"))
                if not Version(after) < version <= Version(upto):
                    continue
            except InvalidVersion:
                continue
            out.append((version, notes_of(str(version), release.get("body") or "")))
        return [n for _, n in sorted(out, key=lambda vn: vn[0], reverse=True)]


def notes_of(version: str, body: str) -> Notes:
    """A release's notes, its changes by heading, each without the scope git cliff puts first (**llm:** …)."""
    new: list[str] = []
    fixed: list[str] = []
    heading = None
    for line in body.splitlines():
        if m := re.match(r"###\s+(.+?)\s*$", line):
            heading = m[1]
        elif heading and (m := re.match(r"-\s+(?:\*\*[^*]+:\*\*\s+)?(.+?)\s*$", line)):
            if heading == "New":
                new.append(m[1])
            elif heading in FIXES:
                fixed.append(m[1])
    return Notes(version, tuple(new), tuple(fixed))
